function fmtMoney(v){
  return (Number(v)||0).toLocaleString('es-ES',{minimumFractionDigits:2,maximumFractionDigits:2}) + ' €';
}
function fmtNum(v, dec=2){
  return (Number(v)||0).toLocaleString('es-ES',{minimumFractionDigits:0,maximumFractionDigits:dec});
}
function escapeHtml(str){
  return String(str==null?'':str).replace(/[&<>"']/g, m => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[m]));
}

// Para insertar texto dentro de un literal JS '...' embebido en un atributo onclick="...".
// Escapa primero las barras invertidas y comillas simples para el JS, y luego escapa para HTML.
function escapeJsAttr(str){
  return escapeHtml(String(str==null?'':str).replace(/\\/g,'\\\\').replace(/'/g,"\\'"));
}

/* ============== Traducción automática de la carta (gratis, con autodetección) ============== */
const CARTA_LANGS = ['es','en','ca'];

function sleep(ms){ return new Promise(r => setTimeout(r, ms)); }

// Traduce un texto al idioma `targetLang` detectando automáticamente el
// idioma de origen (servicio gratuito de Google Translate). Devuelve
// {translated, detected} o null si falla la petición.
async function translateAuto(text, targetLang){
  if(!text || !text.trim()) return null;
  try{
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`;
    const res = await fetch(url);
    const data = await res.json();
    const translated = (data[0]||[]).map(seg => seg[0]).join('');
    const detected = data[2];
    return {translated, detected};
  }catch(e){
    return null;
  }
}

// Traduce automáticamente los nombres de secciones y platos de una carta a los
// idiomas que falten (entre castellano, inglés y catalán), detectando el
// idioma en el que se escribió cada texto. Se ejecuta en segundo plano tras
// guardar la carta, sin bloquear la interfaz.
async function translateField(item){
  if(!item.nombre || !item.nombre.trim()) return false;
  if(!item.i18n) item.i18n = {};
  let detected = item.nombreLang || null;
  let changed = false;
  for(const target of CARTA_LANGS){
    if(detected && target === detected) continue;
    if(item.i18n[target]) continue;
    const r = await translateAuto(item.nombre, target);
    if(!r) continue;
    if(!detected){
      detected = CARTA_LANGS.includes(r.detected) ? r.detected : 'es';
      item.nombreLang = detected;
      changed = true;
      if(target === detected) continue;
    }
    item.i18n[target] = r.translated;
    changed = true;
    await sleep(300);
  }
  return changed;
}

async function autoTranslateCarta(carta){
  let changed = false;
  if(await translateField(carta)) changed = true;
  for(const sec of (carta.secciones||[])){
    if(await translateField(sec)) changed = true;
    for(const p of (sec.platos||[])){
      if(await translateField(p)) changed = true;
      for(const m of (p.modificadores||[])){
        if(await translateField(m)) changed = true;
      }
    }
  }
  if(changed) saveDB();
}

// Traduce las secciones y opciones de un menú (combo) a los idiomas que falten.
async function autoTranslateMenu(menu){
  let changed = false;
  if(await translateField(menu)) changed = true;
  for(const g of (menu.grupos||[])){
    if(await translateField(g)) changed = true;
    for(const o of (g.opciones||[])){
      if(await translateField(o)) changed = true;
    }
  }
  if(changed) saveDB();
}

// Devuelve el nombre de un ítem (sección, plato, menú, opción) en el idioma
// actual de la app, usando la traducción automática guardada (i18n) si existe;
// si no, devuelve el texto original tal cual se escribió.
function tItem(item){
  if(!item) return '';
  const lang = getLang();
  if(item.i18n && item.i18n[lang] && item.i18n[lang].trim()) return item.i18n[lang];
  return item.nombre || '';
}
