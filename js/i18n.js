function toggleLangMenu(ev){
  if(ev) ev.stopPropagation();
  const menu = document.getElementById('lang-menu');
  const btn = document.getElementById('lang-btn');
  if(!menu || !btn) return;
  const opening = menu.style.display === 'none';
  if(opening){
    menu.style.display = 'block';
    const r = btn.getBoundingClientRect();
    menu.style.top = (r.bottom + 4) + 'px';
    menu.style.left = Math.max(4, r.right - menu.offsetWidth) + 'px';
    document.addEventListener('click', closeLangMenuOnce);
  }else{
    menu.style.display = 'none';
  }
}
function closeLangMenuOnce(){
  const menu = document.getElementById('lang-menu');
  if(menu) menu.style.display = 'none';
  document.removeEventListener('click', closeLangMenuOnce);
}
function syncLangButton(){
  const lang = getLang();
  const flagEl = document.getElementById('lang-btn-flag');
  const labelEl = document.getElementById('lang-btn-label');
  if(flagEl) flagEl.innerHTML = LANG_FLAGS[lang] || LANG_FLAGS.es;
  if(labelEl) labelEl.textContent = LANG_NAMES[lang] || LANG_NAMES.es;
  document.querySelectorAll('.lang-menu-item').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}
function t(key){
  const lang = getLang();
  const dict = I18N[lang] || I18N.es;
  if(dict[key] !== undefined) return dict[key];
  return I18N.es[key] !== undefined ? I18N.es[key] : key;
}

// Nombres de los días de la semana SOLO para mostrar en el idioma actual.
// OJO: no usar esto para guardar o comparar datos — para eso sigue existiendo
// la constante WEEK_DAYS (siempre en español), que es como se guardan cosas
// como el día de entrega de un proveedor.
function weekDayFull(idx){ return t('days.full')[idx]; }
function monthFull(idx){ return t('months.full')[idx]; }
function weekDayShort(idx){ return t('days.short')[idx]; }
// Convierte un nombre de día GUARDADO (siempre en español, ej. 'Lunes') a su
// etiqueta traducida para mostrar. No usar para comparar/guardar datos.
function weekDayLabelFromStored(storedName){
  const idx = WEEK_DAYS.indexOf(storedName);
  return idx === -1 ? storedName : weekDayFull(idx);
}

function applyI18n(){
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if(val !== key) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    const val = t(key);
    if(val !== key) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if(val !== key) el.title = val;
  });
}

